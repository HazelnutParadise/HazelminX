// Command fixturegen writes engineering/contracts/fixtures/compose-manifest.json:
// a Compose revision manifest, its digest text, digest and bindings, and a
// grant bound to compose_deploy signed with the public test seed of
// grant.json. Run from core/: go run ./internal/composedeploy/fixturegen
package main

import (
	"crypto/ed25519"
	"encoding/hex"
	"encoding/json"
	"os"

	"github.com/HazelnutParadise/hazelminx/core/internal/composedeploy"
	"github.com/HazelnutParadise/hazelminx/core/internal/grants"
	"github.com/HazelnutParadise/hazelminx/core/internal/protocol"
)

func main() {
	files := map[string][]byte{
		"compose.yaml":     []byte("services:\n  web:\n    image: nginx:1.27\n"),
		"deploy/prod.yaml": []byte("services:\n  web:\n    ports: [\"8080:80\"]\n"),
		"conf/ä b.conf":    []byte("listen 80;\n"),
		"Compose.override": []byte("x\n"),
	}
	m, staged := composedeploy.NewManifest("shop-prod-web", "job_0123456789abcdef01234567", "env:/var/run/docker.sock",
		"compose.yaml", []string{"deploy/prod.yaml"}, []string{"debug", "web.v2"}, "", files)
	seed, _ := hex.DecodeString("0707070707070707070707070707070707070707070707070707070707070707")
	iss := grants.New(ed25519.NewKeyFromSeed(seed), nil)
	g := protocol.ExecutorGrant{ID: "grant-compose-01", Subject: "usr_admin", Permissions: []string{"host.compose.deploy"},
		NotBefore: "2026-11-14T09:30:00Z", ExpiresAt: "2026-11-14T09:40:00Z", Binding: m.Binding("compose_deploy")}
	iss.Sign(&g)
	out := map[string]any{
		"note":           "Generated by core/internal/composedeploy/fixturegen. Test-only key (seed is public, same as grant.json).",
		"manifest":       m,
		"staged":         staged,
		"digestText":     m.DigestText(),
		"digest":         m.Digest(),
		"bindingCheck":   m.Binding("compose_check"),
		"bindingDeploy":  m.Binding("compose_deploy"),
		"grant":          g,
		"grantCanonical": string(grants.Canonical(g)),
	}
	b, _ := json.MarshalIndent(out, "", "  ")
	os.WriteFile("../engineering/contracts/fixtures/compose-manifest.json", append(b, '\n'), 0o644)
}
